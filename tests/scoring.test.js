function wb(sheets) {
  const rows = {};
  Object.keys(sheets).forEach(function (name) { rows[String(name).trim().toLowerCase()] = sheets[name]; });
  return { __rows: rows };
}
function snap(sheets, now) {
  return Sc.buildSnapshot(wb(sheets), now || OCT26);
}
function ctx(snapshot, extra) {
  return Object.assign({ snap: snapshot, techs: {}, cfg: Settings.defaultCfg(), now: OCT26 }, extra || {});
}
function job(o) {
  const map = {
    "job id": o.id || "",
    "job #": o.num || o.id || "",
    "primary technician": o.tech == null ? "Sam Rivera" : o.tech,
    "status": o.status || "Completed",
    "created date": o.created || o.completed || "",
    "completion date": o.completed || "",
    "jobs total revenue": o.rev == null ? 0 : o.rev,
    "opportunity": o.opp == null ? "" : o.opp,
    "converted": o.conv == null ? "" : o.conv,
    "recall": o.recall || "",
    "jobs gross margin": o.gm || 0,
    "total hours worked": o.hrs == null ? 1 : o.hrs,
    "sold hours": o.soldHrs || 0,
    "warranty": o.warr || "",
    "business unit": o.bu || "Service",
    "job type": o.type || "Service Call",
    "lead generated by": o.lead || ""
  };
  return JOB_H.map(function (h) { return map[h.toLowerCase()]; });
}
function show(names) {
  const techs = {};
  names.forEach(function (n) { techs[Sc.key(n)] = { show: true, display: n.split(" ")[0] }; });
  return techs;
}
function person(snapshot, fullName) {
  const t = snapshot.techs[Sc.key(fullName)];
  assert.ok(t, "expected " + fullName + " among " + Object.keys(snapshot.techs).join(", "));
  return t;
}
function withRule(patch, fn) {
  const saved = {};
  Object.keys(patch).forEach(function (k) { saved[k] = Settings.RULES[k]; Settings.RULES[k] = patch[k]; });
  try { return fn(); }
  finally { Object.keys(saved).forEach(function (k) { Settings.RULES[k] = saved[k]; }); }
}

describe("New York dates", function () {
  it("builds wall-clock times on both sides of daylight saving", function () {
    assert.equal(Sc.nyDate(2026, 2, 8, 8, 0, 0).toISOString(), "2026-03-08T12:00:00.000Z");
    assert.equal(Sc.nyDate(2026, 2, 7, 8, 0, 0).toISOString(), "2026-03-07T13:00:00.000Z");
    assert.equal(Sc.nyDate(2026, 10, 1, 8, 0, 0).toISOString(), "2026-11-01T13:00:00.000Z");
  });

  it("treats a date-only value as New York midnight, not UTC midnight", function () {
    const d = Sc.toDate("2026-10-26");
    assert.equal(d.toISOString(), "2026-10-26T04:00:00.000Z");
    assert.equal(Sc.nyYMD(d), "2026-10-26");
    assert.equal(Sc.nyYMD(Sc.toDate("2026-10-26T00:00:00Z")), "2026-10-25");
  });

  it("reads AM/PM and Excel serials as New York wall time", function () {
    assert.equal(Sc.nyParts(Sc.toDate("10/26/2026 12:00 AM")).hh, 0);
    const pm = Sc.nyParts(Sc.toDate("10/26/2026 12:30 PM"));
    assert.equal(pm.hh, 12);
    assert.equal(pm.mm, 30);
    assert.equal(Sc.nyParts(Sc.toDate("10/26/2026 2:30 PM")).hh, 14);
    const serial = (Date.UTC(2026, 9, 26) - Date.UTC(1899, 11, 30)) / 864e5;
    assert.equal(Sc.nyYMD(Sc.toDate(serial)), "2026-10-26");
    const noon = Sc.nyParts(Sc.toDate(serial + 0.5));
    assert.equal(Sc.nyYMD(Sc.toDate(serial + 0.5)), "2026-10-26");
    assert.equal(noon.hh, 12);
  });

  it("keeps a late-evening job on the New York day it was finished", function () {
    const now = Sc.nyDate(2026, 2, 15, 12, 0, 0);
    const s = snap({
      "ST Jobs": [JOB_H, job({ id: "1", completed: "2026-03-01T04:30:00.000Z", rev: 100, created: "2026-02-28" })]
    }, now);
    assert.equal(person(s, "Sam Rivera").y.rev[1], 100);
    assert.equal(person(s, "Sam Rivera").y.rev[2] || 0, 0);
    assert.equal(s.dataThrough, "2026-02-28");

    const evening = snap({
      "ST Jobs": [JOB_H, job({ id: "2", completed: "10/26/2026 11:00 PM", rev: 50 })]
    }, OCT26);
    assert.equal(evening.dataThrough, "2026-10-26");
  });

  it("does not roll a weather day into the next month", function () {
    const s = snap({
      "Weather": [
        ["place", "Norwell, MA"],
        ["temp", 55],
        ["feels", 50],
        ["code", 1],
        ["wind", 4],
        ["updated", "10/26/2026 3:00 PM"],
        ["date", "code", "hi", "lo", "precip"],
        ["2026-10-26", 1, 60, 40, 10]
      ]
    }, OCT26);
    assert.equal(s.weather.days[0].d, "2026-10-26");
  });
});

